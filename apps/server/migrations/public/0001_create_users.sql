CREATE TABLE public.users (
  id uuid PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid,
  updated_by uuid,
  deleted_at timestamptz,
  version integer NOT NULL DEFAULT 0,
  username varchar(64) NOT NULL,
  phone text,
  phone_hash varchar(64),
  email varchar(128),
  real_name varchar(64) NOT NULL,
  password_hash varchar(255) NOT NULL,
  must_change_password boolean NOT NULL DEFAULT true,
  password_changed_at timestamptz,
  status smallint NOT NULL DEFAULT 1,
  failed_attempts integer NOT NULL DEFAULT 0,
  locked_until timestamptz,
  last_identity_id uuid,
  token_version integer NOT NULL DEFAULT 0,
  CONSTRAINT users_phone_pair_check CHECK ((phone IS NULL) = (phone_hash IS NULL)),
  CONSTRAINT users_phone_hash_format_check CHECK (phone_hash ~ '^[0-9a-f]{64}$'),
  CONSTRAINT users_status_check CHECK (status IN (0, 1)),
  CONSTRAINT users_failed_attempts_check CHECK (failed_attempts >= 0),
  CONSTRAINT users_token_version_check CHECK (token_version >= 0),
  CONSTRAINT users_version_check CHECK (version >= 0)
);
